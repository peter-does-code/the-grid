  function format(text, values) {
    if (!values) return text;
    return text.replace(/\{(\w+)\}/g, (match, key) => (values[key] === undefined || values[key] === null ? '' : String(values[key])));
  }

  /** Teksten for en nøgle med {pladsholdere} udfyldt; ukendte nøgler giver `fallback` (eller nøglen selv). */
  function t(key, values, fallback) {
    const text = has(key) ? STRINGS[key] : fallback !== undefined ? fallback : key;
    return format(text, values);
  }

  function has(key) {
    return Object.prototype.hasOwnProperty.call(STRINGS, key);
  }

  /** Alle tekster med nøglen `prefix` + et tal (fx drew.line1, drew.line2, ...), i nummerorden. */
  function numbered(prefix) {
    return Object.keys(STRINGS)
      .filter((key) => key.startsWith(prefix) && /^\d+$/.test(key.slice(prefix.length)))
      .sort((a, b) => Number(a.slice(prefix.length)) - Number(b.slice(prefix.length)))
      .map((key) => STRINGS[key]);
  }

  return { APP_NAME, STRINGS, t, has, format, numbered };
